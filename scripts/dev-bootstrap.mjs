#!/usr/bin/env node
/**
 * `npm run dev:bootstrap` — the first command after a fresh clone
 * (LOCAL_DEVELOPMENT.md §2). Checks prerequisites, brings up the local stack,
 * applies migrations and seeds, and prints the local URLs and credentials.
 *
 * It never contacts a hosted environment: a non-local DIRECT_URL is refused.
 */
import { existsSync } from 'node:fs';

import {
  LOCAL_PORTS,
  SEED_FILE,
  SEEDS_DIR,
  dockerIsRunning,
  fail,
  log,
  logSkip,
  logStep,
  nodeVersionLine,
  portIsFree,
  run,
  startObservability,
  supabase,
  supabaseStatus,
} from './lib/local-stack.mjs';

const printStatus = (status) => {
  logStep('Local services');
  log(`  Product (after \`npm run dev\`)  http://localhost:3000`);
  log(`  Supabase API                    ${status.API_URL ?? '—'}`);
  log(`  Supabase Studio                 ${status.STUDIO_URL ?? '—'}`);
  log(`  Local email (Mailpit)           ${status.MAILPIT_URL ?? '—'}`);
  log(`  Postgres                        ${status.DB_URL ?? '—'}`);
  logStep('Local credentials (disposable, generated by the CLI)');
  log(`  publishable key                 ${status.PUBLISHABLE_KEY ?? '—'}`);
  log(`  secret key (server only)        ${status.SECRET_KEY ?? '—'}`);
};

const main = async () => {
  log('Uspomena local bootstrap\n========================');

  logStep('Prerequisites');
  const node = nodeVersionLine();
  const expectedMajor = Number(node.expected);
  const actualMajor = Number(node.actual.split('.')[0]);
  if (expectedMajor && actualMajor < expectedMajor) {
    fail(`Node ${node.actual} is too old. Install Node ${node.expected} (see .nvmrc) and run again.`);
  }
  log(`  ✓ Node ${node.actual}${expectedMajor && actualMajor !== expectedMajor ? ` (pinned: ${node.expected})` : ''}`);

  const docker = dockerIsRunning();
  if (!docker) {
    fail('Docker is not running. Start Docker Desktop or OrbStack, then run `npm run dev:bootstrap` again.');
  }
  log(`  ✓ Docker ${docker}`);

  let status = supabaseStatus();
  if (!status) {
    logStep('Occupied ports');
    const occupied = [];
    for (const port of [LOCAL_PORTS.api, LOCAL_PORTS.db, LOCAL_PORTS.studio, LOCAL_PORTS.mail]) {
      if (!(await portIsFree(port))) occupied.push(port);
    }
    if (occupied.length > 0) {
      fail(
        `Port(s) ${occupied.join(', ')} are already in use. Stop the conflicting process or change the ports in supabase/config.toml.`,
      );
    }
    log('  ✓ 54321–54324 are free');
  }

  logStep('Local Supabase stack');
  if (status) {
    logSkip('already running');
  } else {
    if (supabase(['start']).status !== 0) fail('`supabase start` failed. See the output above.');
    status = supabaseStatus();
    if (!status) fail('The local Supabase stack did not report its status after starting.');
  }

  logStep('Local observability stack');
  startObservability();

  if (process.env.DIRECT_URL?.trim()) {
    fail(
      'DIRECT_URL is set, but `dev:bootstrap` only prepares the local stack. Unset DIRECT_URL ' +
        'for local development (migrations for other environments are run explicitly in M7/M8).',
    );
  }

  logStep('Migrations');
  if (run('npm', ['run', '--silent', 'db:migrate']).status !== 0) fail('Migrations failed. See the output above.');

  logStep('Seeds');
  const hasSeeds = existsSync(SEED_FILE) || existsSync(SEEDS_DIR);
  if (!hasSeeds) {
    logSkip('no seed files yet (added by the local seed task)');
  } else if (run('npm', ['run', '--silent', 'db:seed']).status !== 0) {
    fail('Seeding failed. See the output above.');
  }

  printStatus(status);
  log('\nNext: run `npm run dev` in a second terminal and open http://localhost:3000');
};

await main();
